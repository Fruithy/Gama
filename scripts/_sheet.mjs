import { chromium } from "@playwright/test";
import { readFileSync } from "node:fs";
const [out, ...names] = process.argv.slice(2);
const imgs = names.map((n) => `<img src="data:image/png;base64,${readFileSync(`.data/shots/smoke-${n}.png`).toString("base64")}"><p>${n}</p>`);
const html = `<html><body style="margin:0;background:#000;display:grid;grid-template-columns:repeat(4,260px);gap:6px;color:#fff;font:12px sans-serif">${imgs.map((i) => `<div>${i}</div>`).join("")}</body><style>img{width:260px;height:563px;display:block}p{margin:2px}</style></html>`;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1060, height: 600 } });
await p.setContent(html);
await p.screenshot({ path: `.data/shots/${out}.png`, fullPage: true });
await b.close();
